-- =====================================================================
--  Миграция 001: случайные номера заказов вместо счётчика AUTO_INCREMENT.
--  Нужна только для баз, установленных до этого изменения
--  (в новых установках schema.sql уже содержит эти правки).
--  Уже существующие заказы сохраняют свои номера.
-- =====================================================================

-- на orders.id ссылаются внешние ключи: тип колонки не меняется,
-- но MySQL разрешает убрать AUTO_INCREMENT только при отключённой проверке FK
SET FOREIGN_KEY_CHECKS = 0;
ALTER TABLE orders MODIFY id INT UNSIGNED NOT NULL COMMENT 'случайный номер 100000–999999';
SET FOREIGN_KEY_CHECKS = 1;

ALTER TABLE orders ADD KEY ix_orders_created (created_at);
